  def get_word_list(:en, :medium), do: @english_medium
  def get_word_list(:en, :long), do: @english_long
  def get_word_list(:ru, :short), do: @russian_short
  def get_word_list(:ru, :medium), do: @russian_medium
  def get_word_list(:ru, :long), do: @russian_long
end
