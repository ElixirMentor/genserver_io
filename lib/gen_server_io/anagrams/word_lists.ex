  @doc """
  Gets a random base word for the given language and length category.
  Excludes words that have already been used.
  If all words have been used, resets and returns a random word from the full list.
  """
  def random_word(language, category, used_words \\ MapSet.new()) do
    words = get_word_list(language, category)
    available_words = Enum.reject(words, fn word -> MapSet.member?(used_words, word) end)

    case available_words do
      [] ->
        # All words used, pick from full list (game will reset used_words)
        Enum.random(words)

      available ->
        Enum.random(available)
    end
  end

  @doc """
  Gets the word list for the given language and category.
  """
